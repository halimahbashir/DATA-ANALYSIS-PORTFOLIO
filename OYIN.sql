CREATE DATABASE superstore;
USE superstore;

SET SQL_SAFE_UPDATES=1;
SET GLOBAL MAX_ALLOWED_PACKET =67108864;

SELECT * FROM superstore.`sample__superstore`;

SELECT 
COUNT(*) AS TOTAL_TRANSACTION,
COUNT(DISTINCT ORDER_ID)
AS TOTAL_ORDER,
COUNT(DISTINCT PRODUCT_ID)
AS TOTAL_PRODUCT,
SUM(SALES) AS TOTAL_SALES,
SUM(PROFIT) AS TOTAL_PROFIT,
SUM(DISCOUNT) AS TOTAL_DISCOUNT,
SUM(QUANTITY) AS TOTOAL_QUANTITY,
AVG(DISCOUNT) AS AVERAGE_DISCOUNT
FROM superstore.`sample__superstore`;

SELECT
CATEGORY,
SUM(SALES) AS TOTAL_SALES,
SUM(PROFIT) AS TOTAL_PROFIT,
SUM(QUANTITY) AS TOTAL_QUANTITY,
ROUND(SUM(PROFIT)/SUM(SALES)* 100,2)
AS PROFIT_MARGIN
FROM superstore.`sample__superstore`
GROUP BY CATEGORY
ORDER BY TOTAL_SALES DESC;

SELECT
STATE,
SUM(SALES) AS TOTAL_SALES,
SUM(PROFIT) AS TOTAL_PROFIT,
SUM(QUANTITY) AS TOTAL_QUANTITY,
AVG(DISCOUNT) AS AVERAGE_DISCOUNT FROM  superstore.`sample__superstore`
GROUP BY STATE
ORDER BY TOTAL_SALES ASC
LIMIT 10;

SELECT
PRODUCT_ID,
`PRODUCT NAME` AS PRODUCT_NAME,
CATEGORY,
`sub-category` AS SUB_CATEGORY,
SUM(SALES) AS TOTAL_SALES,
SUM(PROFIT) AS TOTAL_PROFIT,
SUM(QUANTITY) AS TOTAL_QUANTITY
FROM superstore.`sample__superstore`
GROUP BY PRODUCT_ID,`PRODUCT NAME`,CATEGORY,`SUB-CATEGORY`
ORDER BY TOTAL_SALES DESC;

SELECT
REGION,
SUM(SALES) AS TOTAL_SALES,
SUM(PROFIT) AS TOTAL_PROFIT,
SUM(QUANTITY) AS TOTAL_QUANTITY,
AVG(DISCOUNT) AS AVERAGE_DISCOUNT FROM  superstore.`sample__superstore`
GROUP BY REGION
ORDER BY TOTAL_SALES DESC;

SELECT
SEGMENT,
SUM(SALES) AS TOTAL_SALES,
SUM(PROFIT) AS TOTAL_PROFIT,
SUM(QUANTITY) AS TOTAL_QUANTITY
FROM superstore.`sample__superstore`
GROUP BY SEGMENT
ORDER BY TOTAL_SALES DESC;

SELECT
YEAR(Order_Date) AS ORDER_YEAR,
MONTH(Order_Date) AS ORDER_MONTH,
SUM(SALES) AS TOTAL_SALES,
SUM(PROFIT) AS TOTAL_PROFIT
FROM superstore.`sample__superstore`
GROUP BY YEAR(Order_Date),MONTH(Order_Date)
ORDER BY ORDER_YEAR,ORDER_MONTH;

SELECT
SHIP_MODE,
SUM(SALES) AS TOTAL_SALES,
SUM(PROFIT) AS TOTAL_PROFIT,
COUNT(*) AS TOTAL_ORDERS
FROM superstore.`sample__superstore`
GROUP BY SHIP_MODE
ORDER BY TOTAL_SALES DESC;

SELECT
DISCOUNT,
SUM(SALES) AS TOTAL_SALES,
SUM(PROFIT) AS TOTAL_PROFIT,
COUNT(*) AS TOTAL_TRANSACTIONS
FROM superstore.`sample__superstore`
GROUP BY DISCOUNT
ORDER BY DISCOUNT ASC;

SELECT
SUM(SALES) AS TOTAL_SALES
FROM superstore.`sample__superstore`;

SELECT
COUNT(DISTINCT `CUSTOMER ID`)
FROM superstore.`sample__superstore`;

SELECT
COUNT(*) AS TOTAL_TRANSACTION
FROM superstore.`sample__superstore`;

